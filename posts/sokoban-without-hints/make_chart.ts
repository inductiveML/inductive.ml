// Draws the held-out learning-curve figure for "Sokoban Without Hints" from the
// logged evaluation files in ./data, writes it to heldout_curve.svg, and inlines
// the same SVG into the post between its chart markers.
//
//   bun run posts/sokoban-without-hints/make_chart.ts
//
// Data (copied verbatim from avp1598/sokoban @ e189e5b91b25f9544f32dd557f8d977106a5b0cd):
//   data/avp1598-sokoban/unit13_partB.json        <- results/unit13/partB.json (WD2, WD3)
//   data/avp1598-sokoban/unit15_P_long_eval/*.json <- results/unit15/eval/P_long_s1_*_unf_heldout20k_summary.json
// All three runs are scored on the same 20,000 held-out unfiltered levels, sampled play.

import {readFile, readdir, writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';
import {z} from 'zod';

const here = import.meta.dir;
const dataDir = resolve(here, 'data/avp1598-sokoban');
const postPath = resolve(here, '../sokoban-without-hints.md');
const svgPath = resolve(here, 'heldout_curve.svg');

const START_MARKER = '<!-- heldout-chart:start (generated by posts/sokoban-without-hints/make_chart.ts) -->';
const END_MARKER = '<!-- heldout-chart:end -->';

const PartBSchema = z.object({
	table: z.array(
		z.object({
			run: z.enum(['WD2', 'WD3']),
			step: z.number().int().positive(),
			heldout: z.number().min(0).max(1),
		}),
	),
});

const EvalSummarySchema = z.object({
	step: z.number().int().positive(),
	set: z.literal('unf_heldout20k'),
	sampled: z.tuple([z.number().int().nonnegative(), z.literal(20000), z.number(), z.number()]),
});

interface Point {
	step: number;
	rate: number;
}

interface Series {
	key: string;
	legend: string;
	color: string;
	dash: string;
	points: Point[];
}

// The plot ends at WD3's last checkpoint (8.5B, where its flat-stop rule ended it).
// WD2 kept training to 12B; the caption gives its value there.
const MAX_STEP = 8_502_902_784;

async function loadPartB(): Promise<{wd2: Point[]; wd3: Point[]}> {
	const parsed = PartBSchema.parse(JSON.parse(await readFile(resolve(dataDir, 'unit13_partB.json'), 'utf8')));
	const pick = (run: 'WD2' | 'WD3'): Point[] =>
		parsed.table
			.filter((row) => row.run === run && row.step <= MAX_STEP)
			.map((row) => ({step: row.step, rate: row.heldout}))
			.sort((a, b) => a.step - b.step);
	return {wd2: pick('WD2'), wd3: pick('WD3')};
}

async function loadPLong(): Promise<Point[]> {
	const dir = resolve(dataDir, 'unit15_P_long_eval');
	const names = (await readdir(dir)).filter((name) => /^P_long_s1_\d+_unf_heldout20k_summary\.json$/.test(name));
	if (names.length !== 16) throw new Error(`expected 16 P-long summaries, found ${names.length}`);
	const points: Point[] = [];
	for (const name of names) {
		const summary = EvalSummarySchema.parse(JSON.parse(await readFile(resolve(dir, name), 'utf8')));
		const [solved, total] = summary.sampled;
		points.push({step: summary.step, rate: solved / total});
	}
	return points.sort((a, b) => a.step - b.step);
}

// Geometry, in SVG user units. 400 wide so labels stay legible on phones.
const W = 400;
const H = 300;
const LEGEND_TOP = 14;
const LEGEND_ROW = 17;
const PLOT_LEFT = 38;
const PLOT_RIGHT = W - 46;
const PLOT_TOP = LEGEND_TOP + 3 * LEGEND_ROW + 10;
const PLOT_BOTTOM = H - 40;

const xScale = (step: number): number => PLOT_LEFT + (step / MAX_STEP) * (PLOT_RIGHT - PLOT_LEFT);
const yScale = (rate: number): number => PLOT_BOTTOM - rate * (PLOT_BOTTOM - PLOT_TOP);
const fmt = (n: number): string => n.toFixed(1);
const pct = (rate: number): string => `${(rate * 100).toFixed(1)}%`;

const FONT = 'Archivo, system-ui, sans-serif';

function renderSvg(series: Series[]): string {
	const parts: string[] = [];
	const label = series.map((s) => `${s.legend}: ${pct(s.points[s.points.length - 1].rate)} at the last checkpoint`).join('; ');
	parts.push(
		`<svg viewBox="0 0 ${W} ${H}" width="100%" role="img" aria-label="Held-out solve rate against training steps. ${label}." style="max-width:640px;height:auto;color:inherit" xmlns="http://www.w3.org/2000/svg">`,
	);

	// Grid and y axis labels.
	parts.push(`<g stroke="currentColor" stroke-opacity="0.15" stroke-width="1">`);
	for (const tick of [0, 0.2, 0.4, 0.6, 0.8, 1]) {
		parts.push(`<path d="M${PLOT_LEFT} ${fmt(yScale(tick))} H${PLOT_RIGHT}"/>`);
	}
	parts.push(`</g>`);
	parts.push(`<g fill="currentColor" font-family="${FONT}" font-size="11" opacity="0.75">`);
	for (const tick of [0, 0.2, 0.4, 0.6, 0.8, 1]) {
		parts.push(`<text x="${PLOT_LEFT - 6}" y="${fmt(yScale(tick) + 4)}" text-anchor="end">${tick * 100}%</text>`);
	}
	for (const billions of [0, 2, 4, 6, 8]) {
		parts.push(`<text x="${fmt(xScale(billions * 1e9))}" y="${PLOT_BOTTOM + 16}" text-anchor="middle">${billions}B</text>`);
	}
	parts.push(
		`<text x="${fmt((PLOT_LEFT + PLOT_RIGHT) / 2)}" y="${PLOT_BOTTOM + 33}" text-anchor="middle">training steps</text>`,
	);
	parts.push(`</g>`);
	parts.push(
		`<path d="M${PLOT_LEFT} ${PLOT_BOTTOM} H${PLOT_RIGHT}" stroke="currentColor" stroke-opacity="0.6" stroke-width="1"/>`,
	);

	// Legend: one row per series, swatch drawn the same way as the line.
	series.forEach((s, i) => {
		const y = LEGEND_TOP + i * LEGEND_ROW;
		parts.push(
			`<path d="M${PLOT_LEFT} ${y} H${PLOT_LEFT + 22}" stroke="${s.color}" stroke-width="2" stroke-dasharray="${s.dash}"/>`,
			`<circle cx="${PLOT_LEFT + 11}" cy="${y}" r="4" fill="${s.color}" stroke="#f3eee4" stroke-width="2"/>`,
			`<text x="${PLOT_LEFT + 30}" y="${y + 4}" fill="currentColor" font-family="${FONT}" font-size="12">${s.legend}</text>`,
		);
	});

	// Lines, then markers with a 2px surface ring, then end-value labels in text ink.
	for (const s of series) {
		const d = s.points.map((p, i) => `${i === 0 ? 'M' : 'L'}${fmt(xScale(p.step))} ${fmt(yScale(p.rate))}`).join(' ');
		parts.push(
			`<path d="${d}" fill="none" stroke="${s.color}" stroke-width="2" stroke-linejoin="round" stroke-dasharray="${s.dash}"/>`,
		);
	}
	for (const s of series) {
		parts.push(`<g fill="${s.color}" stroke="#f3eee4" stroke-width="2">`);
		for (const p of s.points) {
			parts.push(`<circle cx="${fmt(xScale(p.step))}" cy="${fmt(yScale(p.rate))}" r="4"><title>${s.legend}, ${(p.step / 1e9).toFixed(2)}B steps: ${pct(p.rate)}</title></circle>`);
		}
		parts.push(`</g>`);
	}

	// End labels: keep at least 14 units apart so the two upper series never overlap.
	const ends = series
		.map((s) => {
			const last = s.points[s.points.length - 1];
			return {x: xScale(last.step), y: yScale(last.rate), text: pct(last.rate)};
		})
		.sort((a, b) => a.y - b.y);
	for (let i = 1; i < ends.length; i++) {
		if (ends[i].y - ends[i - 1].y < 14) ends[i].y = ends[i - 1].y + 14;
	}
	parts.push(`<g fill="currentColor" font-family="${FONT}" font-size="11">`);
	for (const end of ends) {
		parts.push(`<text x="${fmt(end.x + 8)}" y="${fmt(end.y + 4)}">${end.text}</text>`);
	}
	parts.push(`</g>`);

	parts.push(`</svg>`);
	return parts.join('\n');
}

const {wd2, wd3} = await loadPartB();
const pLong = await loadPLong();

// Colours: validated as a categorical set on the site's paper surface (#f3eee4)
// with the dataviz palette validator; amber is under 3:1 contrast, so every
// series is also named in the legend and carries a direct end label.
const series: Series[] = [
	{key: 'WD2', legend: 'Curriculum, trace clip 5 (bug)', color: '#eda100', dash: '5 3', points: wd2},
	{key: 'WD3', legend: 'Curriculum, trace clip 1 (fixed)', color: '#2a78d6', dash: 'none', points: wd3},
	{key: 'P-long', legend: 'No curriculum, trace clip 1', color: '#b8381f', dash: 'none', points: pLong},
];

const svg = renderSvg(series);
await writeFile(svgPath, svg + '\n');

const post = await readFile(postPath, 'utf8');
const start = post.indexOf(START_MARKER);
const end = post.indexOf(END_MARKER);
if (start === -1 || end === -1 || end < start) throw new Error('chart markers not found in the post');
const updated = post.slice(0, start + START_MARKER.length) + '\n' + svg + '\n' + post.slice(end);
await writeFile(postPath, updated);

for (const s of series) {
	console.log(`${s.key}: ${s.points.map((p) => `${(p.step / 1e9).toFixed(2)}B ${pct(p.rate)}`).join(', ')}`);
}
console.log(`wrote ${svgPath} and inlined it into ${postPath}`);
